# ============================================================
# 主程式
# ============================================================

def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    results = []

    for segment_id, data in SEGMENTS.items():
        name = data["name"]
        stations = data["stations"]

        station_count, length = generate_geojson(segment_id, name, stations)
        results.append({
            "segment_id": segment_id,
            "name": name,
            "stations": station_count,
            "length_km": round(length, 2),
            "status": "draft"
        })

        print(f"✅ {segment_id}: {name} ({station_count} 站, {length:.1f} km)")

    # 產生摘要 JSON
    summary = {
        "generated_at": "auto",
        "total_segments": len(results),
        "segments": results
    }

    with open(os.path.join(OUTPUT_DIR, "_summary.json"), 'w', encoding='utf-8') as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)

    print(f"\n✅ 已產生 {len(results)} 個草稿檔案於 {OUTPUT_DIR}/")

if __name__ == "__main__":
    main()
