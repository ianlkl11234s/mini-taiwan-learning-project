import json
import os
import math

OUTPUT_DIR = "public/data-tra/tracks/drafts"

def calculate_length_km(coords):
    """計算軌道長度"""
    total = 0
    for i in range(len(coords) - 1):
        lon1, lat1 = coords[i]
        lon2, lat2 = coords[i + 1]
        R = 6371
        dlat, dlon = math.radians(lat2 - lat1), math.radians(lon2 - lon1)
        a = math.sin(dlat/2)**2 + math.cos(math.radians(lat1)) * math.cos(math.radians(lat2)) * math.sin(dlon/2)**2
        total += R * 2 * math.asin(math.sqrt(a))
    return total

def generate_geojson(segment_id, name, stations):
    """產生 GeoJSON"""
    coords = [[lon, lat] for _, lon, lat in stations]

    geojson = {
        "type": "FeatureCollection",
        "features": [{
            "type": "Feature",
            "properties": {
                "segment_id": segment_id,
                "name": name,
                "station_count": len(stations),
                "stations": [s[0] for s in stations],
                "status": "draft"
            },
            "geometry": {
                "type": "LineString",
                "coordinates": coords
            }
        }]
    }

    filepath = os.path.join(OUTPUT_DIR, f"{segment_id}.geojson")
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(geojson, f, indent=2, ensure_ascii=False)

    length = calculate_length_km([(c[0], c[1]) for c in coords])
    return len(stations), length

